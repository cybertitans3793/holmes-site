def prep_sim(key):
    s = SIMS[key]
    h = open(os.path.join(SP, s['file']), encoding='utf-8').read()
    kind = s.get('kind', 'plain')
    if (kind == 'xl' and LISTEN in h) or (kind == 'panel' and PANEL_CSS in h): return h  # already prepared (recovered from a built page)
    if kind == 'xl':
        n = 0
        for a, b in [('window.innerHeight / 718', 'window.innerHeight / 676'), ('(718 * s - 718)', '(676 * s - 676)')]:
            assert a in h, (key, a); h = h.replace(a, b); n += 1
        h = h.replace('"Lucida Sans","Lucida Grande",Arial', '"Space Grotesk",Arial').replace('"Lucida Sans",Arial', '"Space Grotesk",Arial')
        h = h.replace('</head>', FONTS + XL_CSS + '</head>', 1).replace('</body>', LISTEN + '</body>', 1)
    elif kind == 'panel':
        h = h.replace('</head>', FONTS + PANEL_CSS + '</head>', 1)
    assert '</head>' in h or kind == 'plain'
    return h

def js_str(s):
    return json.dumps(s, ensure_ascii=False).replace('</', '<\\/').replace('<!--', '<\\!--')

