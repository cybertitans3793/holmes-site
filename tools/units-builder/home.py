#!/usr/bin/env python3
"""Builds units/HOME.html, the "Pick your class" homepage (design option A, Big Type).
Unit list and "has sims" flags come from units.py, so the homepage stays in step with the unit pages.
Links go to the Site pages, whose custom paths are the lower-case unit codes (…/holmes/p1-04)."""
import html, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from units import UNITS

SITE = 'https://sites.google.com/fcps.org/holmes/'
COURSES = [  # (big label, course name, code prefix, line under the unit count)
    ('AB', 'Algebra-Based Physics', 'AB', '9th grade'),
    ('P1', 'AP Physics 1 / IB', 'P1', 'AP 1 + IB Physics'),
    ('P2', 'AP Physics 2 / IB', 'P2', 'AP 2 + IB Physics'),
]
E = html.escape
# Hand-built unit pages that aren't generated from units.py
EXTRA = {'P1-06': {'title': 'Work, Power, and Energy', 'tabs': [1]}, 'P1-07': {'title': 'Impulse and Momentum', 'tabs': [1]}}

def card(big, name, prefix, sub, hot):
    units = sorted((k, v) for k, v in {**UNITS, **EXTRA}.items() if k.startswith(prefix + '-'))
    rows = []
    for k, u in units:
        ready = bool(u.get('tabs'))
        rows.append(f'<a class="row{"" if ready else " soon"}" href="{SITE}{k.lower()}" target="_top">'
                    f'<span class="code">{k}</span><span class="nm">{E(u["title"])}</span>'
                    f'{"" if ready else "<span class=tag>SOON</span>"}</a>')
    return (f'<section class="card{" hot" if hot else ""}"><div class="top"><div class="line"><div class="big">{big}</div>'
            f'<div class="meta">{len(units)} UNITS<br>{E(sub.upper())}</div></div><h2>{E(name)}</h2></div>'
            f'<nav class="list" aria-label="{E(name)} units">{"".join(rows)}</nav></section>')

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Holmes Physics</title>
<!-- Holmes Physics homepage, generated by tools/units-builder/home.py. Rebuild rather than editing this file. -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Space+Grotesk:wght@400;500;700&family=IBM+Plex+Mono:wght@500;700&display=swap">
<style>
:root{--bg:#fafafa;--ink:#111;--muted:#8a8a8a;--hot:#ff6a2b;--soft:#ffe2d3;--f-mono:"IBM Plex Mono",ui-monospace,Menlo,Consolas,monospace;color-scheme:light}
*{box-sizing:border-box}
html,body{margin:0;background:var(--bg);color:var(--ink);font:16px/1.45 "Space Grotesk",system-ui,-apple-system,"Segoe UI",Roboto,Arial,sans-serif}
main{max-width:1200px;margin:0 auto;padding:30px 16px 40px}
.kicker{font:700 13px var(--f-mono);letter-spacing:.02em}
h1{margin:8px 0 26px;font-size:clamp(48px,8vw,76px);line-height:.9;letter-spacing:-.04em;font-weight:700}
.cards{display:flex;flex-wrap:wrap;gap:22px;align-items:flex-start}
.card{flex:1 1 300px;min-width:0;border:3px solid var(--ink);background:#fff;box-shadow:6px 6px 0 var(--ink)}
.card.hot{box-shadow:8px 8px 0 var(--hot)}
.top{padding:16px 18px 12px;border-bottom:3px solid var(--ink)}
.hot .top{background:var(--ink);color:var(--bg)}
.line{display:flex;align-items:flex-end;justify-content:space-between;gap:10px}
.big{font-size:clamp(72px,9vw,92px);font-weight:700;line-height:.8;letter-spacing:-.05em}
.meta{font:700 12px var(--f-mono);text-align:right}
h2{margin:12px 0 0;font-size:26px;line-height:1.05;letter-spacing:-.02em}
.list{padding:6px 18px 14px}
.row{display:flex;align-items:baseline;gap:10px;padding:8px 0;border-top:1px solid #e3e3e3;text-decoration:none;color:var(--ink);font-size:15px;font-weight:500}
.row:first-child{border-top:0}
.row:hover{background:var(--soft);box-shadow:-8px 0 0 var(--soft),8px 0 0 var(--soft)}
.row:focus-visible{outline:3px solid var(--hot);outline-offset:2px}
.row .code{font:700 12px var(--f-mono);width:44px;flex:none}
.row.soon{color:var(--muted)}
.tag{font:700 11px var(--f-mono);color:var(--muted);margin-left:auto;white-space:nowrap}
.foot{margin-top:28px;font:500 12px/1.5 var(--f-mono);color:#4a4a4a}
</style>
</head>
<body>
<main>
<div class="kicker">MR. HOLMES · URBANA HIGH SCHOOL · PHYSICS</div>
<h1>Pick your class.</h1>
<div class="cards">
{cards}
</div>
<p class="foot">SOON = sims for that unit are on the way. Each unit page has its sims and things to try; AP 1 units also have practice questions.</p>
</main>
</body>
</html>
"""

if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else 'HOME.html'
    cards = '\n'.join(card(b, n, p, s, p == 'P1') for b, n, p, s in COURSES)
    open(out, 'w', encoding='utf-8').write(PAGE.replace('{cards}', cards))
    print('ok', out)
